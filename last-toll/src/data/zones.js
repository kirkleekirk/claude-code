export function zoneById(id) {
  return ZONES.find((z) => z.id === id) || ZONES[0];
}

// When a raid starts and when the Sweep hits, in hours.
export function zoneClock(zone) {
  const start = zone.night ? 21.0 : 17.0;
  return { start, sweep: start + 2.5, overrun: start + 3.75 };
}

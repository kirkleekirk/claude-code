export const LINE_H = 10;
export const CELL_H = 9;

const parsed = {};
let atlasX = 0;
for (const [ch, def] of Object.entries(GLYPHS)) {
  const rows = def.split('|');
  const w = rows[0].length;
  parsed[ch] = { rows, w, x: atlasX };
  atlasX += w + 1;
}
const ATLAS_W = atlasX;
const atlases = new Map();

function atlasFor(color) {
  let a = atlases.get(color);
  if (a) return a;
  a = createCanvas(ATLAS_W, CELL_H);
  const c = a.getContext('2d');
  c.fillStyle = color;
  for (const g of Object.values(parsed)) {
    g.rows.forEach((row, y) => { for (let x = 0; x < row.length; x++) if (row[x] === '#') c.fillRect(g.x + x, y, 1, 1); });
  }
  atlases.set(color, a);
  return a;
}

const glyph = (ch) => parsed[ch] || parsed['?'];

export function measure(str, scale = 1) {
  let w = 0;
  for (const ch of String(str)) w += glyph(ch).w + 1;
  return Math.max(0, w - 1) * scale;
}

// opts: align ('left'|'center'|'right'), shadow (colour), scale (int), maxW (truncates with an ellipsis)
export function drawText(ctx, str, x, y, color, opts = {}) {
  let s = String(str);
  const scale = opts.scale || 1;
  if (opts.maxW && measure(s, scale) > opts.maxW) {
    while (s.length > 1 && measure(s + '…', scale) > opts.maxW) s = s.slice(0, -1);
    s += '…';
  }
  const w = measure(s, scale);
  let cx = Math.round(opts.align === 'center' ? x - w / 2 : opts.align === 'right' ? x - w : x);
  const cy = Math.round(y);
  if (opts.shadow) drawRun(ctx, s, cx + scale, cy + scale, opts.shadow, scale);
  drawRun(ctx, s, cx, cy, color, scale);
  return w;
}

function drawRun(ctx, s, x, y, color, scale) {
  const a = atlasFor(color);
  for (const ch of s) {
    const g = glyph(ch);
    if (ch !== ' ') ctx.drawImage(a, g.x, 0, g.w, CELL_H, x, y, g.w * scale, CELL_H * scale);
    x += (g.w + 1) * scale;
  }
}

export function wrap(str, maxW) {
  const out = [];
  for (const para of String(str).split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const w of words) {
      const t = line ? line + ' ' + w : w;
      if (measure(t) > maxW && line) { out.push(line); line = w; } else line = t;
    }
    out.push(line);
  }
  return out;
}

export function drawWrapped(ctx, str, x, y, maxW, color, opts = {}) {
  const lines = wrap(str, maxW);
  const lh = opts.lineH || LINE_H;
  lines.forEach((l, i) => drawText(ctx, l, x, y + i * lh, color, opts));
  return lines.length * lh;
}

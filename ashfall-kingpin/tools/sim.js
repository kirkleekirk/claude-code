#!/usr/bin/env node
// Headless balance sim: greedy bot plays N game days on several seeds, reports time-to-rank
// (real minutes at 1x: 1 game day = 6 min), money curves and bottlenecks, asserts the targets
// and writes docs/BALANCE_REPORT.md. `--stress 1000` runs a long stability check.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { newGame } from '../src/sim/state.js';
import { advance } from '../src/sim/sim.js';
import { botHour } from '../src/sim/bot.js';
import { validate, serialize, deserialize } from '../src/sim/save.js';
import { buildWorld } from '../src/world/worldgen.js';
import { RANKS } from '../src/data/progress.js';
import { SETTLEMENT_IDS } from '../src/data/places.js';
import { holds } from '../src/sim/jobs.js';
import { cleanAssets } from '../src/sim/business.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const args = process.argv.slice(2);
const arg = (k, d) => { const i = args.indexOf(k); return i >= 0 ? +args[i + 1] : d; };
const DAYS = arg('--days', 60);
const SEEDS = arg('--seeds', 3);
const STRESS = arg('--stress', 0);

const TARGETS = [null, [25, 40], [75, 105], [150, 180], [210, 270], [300, 360]];

const W = buildWorld();
const lots = {};
for (const t of SETTLEMENT_IDS) lots[t] = W.buildings.filter((b) => b.place === t && b.lot).map((b) => b.id);
const B = { lotOf: (town, k) => (lots[town] || [])[k] ?? 9999 };

function run(seed, days, opts = {}) {
  const S = newGame(seed, 'normal', { tutorial: true });
  const curve = [];
  const errs = [];
  const t0 = Date.now();
  for (let h = 0; h < days * 24; h++) {
    botHour(S, B);
    advance(S, 60);
    S._fx = [];
    if (h % 24 === 0) {
      curve.push({ day: S.day, dirty: Math.round(S.money.dirty + S.money.carried), clean: Math.round(S.money.clean), rep: Math.round(S.rep), crew: S.crew.length, fronts: S.businesses.length, heat: S.notoriety });
      const e = validate(S);
      if (e.length) { errs.push(`day ${S.day}: ${e.join('; ')}`); if (errs.length > 5) break; }
    }
    if (opts.stopAtEnding && S.ending) break;
    if (Date.now() - t0 > 240000) { errs.push('timeout (possible infinite loop)'); break; }
  }
  const rt = S.stats.rankDay || {};
  const minutes = {};
  for (let r = 1; r < RANKS.length; r++) if (rt[r] !== undefined) minutes[r] = (rt[r] / 1440) * 6;
  return { seed, S, curve, errs, minutes, ms: Date.now() - t0 };
}

function median(a) { const s = a.map((x) => (x === undefined ? Infinity : x)).sort((x, y) => x - y); const m = s[Math.floor(s.length / 2)]; return m === Infinity ? undefined : m; }

if (STRESS) {
  const r = run(7, STRESS);
  const S = r.S;
  const rt = serialize(deserialize(serialize(S))) === serialize(S);
  console.log(`Stress ${STRESS} days: ${r.ms} ms, day ${S.day}, rank ${RANKS[r.S.rep >= 7000 ? 5 : 0].name}, errors: ${r.errs.length ? r.errs.join(' | ') : 'none'}, save round-trip: ${rt}`);
  process.exit(r.errs.length || !rt ? 1 : 0);
}

const runs = [];
for (let i = 0; i < SEEDS; i++) runs.push(run(1000 + i * 77, DAYS));
const lines = [];
lines.push('# Balance Report', '', `Generated by \`node tools/sim.js\` (${SEEDS} seeds x ${DAYS} game days, greedy bot, Normal). 1 game day = 6 real minutes at 1x.`, '');
lines.push('## Time to rank (real minutes at 1x)', '', '| Rank | Target | ' + runs.map((r) => `Seed ${r.seed}`).join(' | ') + ' | Median | Pass |', '|---|---|' + runs.map(() => '---|').join('') + '---|---|');
let pass = true;
for (let r = 1; r < RANKS.length; r++) {
  const vals = runs.map((x) => x.minutes[r]);
  const med = median(vals);
  const [lo, hi] = TARGETS[r];
  const ok = med !== undefined && med >= lo && med <= hi;
  if (!ok) pass = false;
  lines.push(`| ${RANKS[r].name} | ${lo}-${hi} | ${vals.map((v) => (v === undefined ? 'not reached' : v.toFixed(0))).join(' | ')} | ${med === undefined ? '-' : med.toFixed(0)} | ${ok ? 'yes' : 'NO'} |`);
}
const S0 = runs[0].S;
lines.push('', '## Money curve (seed ' + runs[0].seed + ')', '', '| Day | Dirty | Clean | REP | Crew | Fronts | Notoriety |', '|---|---|---|---|---|---|---|');
for (const c of runs[0].curve.filter((c, i) => i % 5 === 0 || i === runs[0].curve.length - 1)) lines.push(`| ${c.day} | $${c.dirty.toLocaleString()} | $${c.clean.toLocaleString()} | ${c.rep} | ${c.crew} | ${c.fronts} | ${c.heat} |`);
lines.push('', '## End state (seed ' + runs[0].seed + ')', '');
lines.push(`- Day ${S0.day}, REP ${Math.round(S0.rep)}, level ${S0.level}, holds ${holds(S0).length}, clean assets $${Math.round(cleanAssets(S0)).toLocaleString()}, ending: ${S0.ending || 'none yet'}`);
const inc = {};
for (const h of S0.hist.slice(-10)) for (const [k, v] of Object.entries(h.inc || {})) inc[k] = (inc[k] || 0) + v;
lines.push('- Income mix, last 10 days: ' + Object.entries(inc).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} $${Math.round(v).toLocaleString()}`).join(', '));
const st = S0.stats;
lines.push(`- Units sold ${Math.round(st.unitsSold || 0)}, guns crafted ${st.gunsCrafted || 0}, contracts ${st.contractsDone || 0}/${(st.contractsDone || 0) + (st.contractsFailed || 0)}, vaults ${st.vaults || 0}, audits ${st.audits || 0}, crackdowns ${st.crackdowns || 0}, defenses ${st.defensesWon || 0}W/${st.defensesLost || 0}L`);
lines.push('', '## REP by source (all seeds)', '', '| Source | ' + runs.map((r) => 'Seed ' + r.seed).join(' | ') + ' |', '|---|' + runs.map(() => '---|').join(''));
const cats = [...new Set(runs.flatMap((r) => Object.keys(r.S.stats.repBy || {})))].sort((a, b) => (runs[0].S.stats.repBy[b] || 0) - (runs[0].S.stats.repBy[a] || 0));
for (const c of cats) lines.push(`| ${c} | ` + runs.map((r) => Math.round((r.S.stats.repBy || {})[c] || 0)).join(' | ') + ' |');
lines.push('', '## Bottlenecks observed', '');
const notes = [];
if (!runs.every((r) => r.minutes[1] !== undefined)) notes.push('- Some seeds never reached Hustler: early income too slow.');
if ((st.audits || 0) > 6) notes.push('- Frequent audits: laundering pushes past capacity.');
if ((st.defensesLost || 0) > (st.defensesWon || 0)) notes.push('- Hollow defense loses more than it wins: guards/turrets underbuilt.');
if (!notes.length) notes.push('- None blocking: every rank reachable, no stalls in the money curve.');
lines.push(...notes);
const errs = runs.flatMap((r) => r.errs);
lines.push('', '## Integrity', '', errs.length ? errs.map((e) => '- ' + e).join('\n') : '- No NaN, no negative inventory or money, no stalls.', '', `Result: **${pass ? 'PASS' : 'FAIL'}**`, '');
fs.writeFileSync(path.join(ROOT, 'docs', 'BALANCE_REPORT.md'), lines.join('\n'));
console.log(lines.slice(4, 4 + RANKS.length + 3).join('\n'));
console.log(errs.length ? 'ERRORS: ' + errs.join(' | ') : 'integrity ok', '| runtime', runs.map((r) => r.ms + 'ms').join(' '));
console.log('Result:', pass ? 'PASS' : 'FAIL');
process.exit(pass && !errs.length ? 0 : 1);
